/**
 * One-time local setup: creates the `nabz` database role and the nabz_dev / nabz_test databases,
 * generates secrets, and writes .env.local. Safe to run again (it only fills in what's missing).
 *
 * Needs a Postgres superuser once, read from .env.bootstrap.local:
 *   PG_SUPERUSER_URL=postgres://postgres:<password>@127.0.0.1:5432/postgres
 * That file is deleted after a successful run; the app itself never uses the superuser.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import pg from "pg";
import { LOCAL_DATABASES, parseDatabaseUrl } from "../../src/lib/db/local-guard";
import { loadLocalEnv, runScript } from "./_env";

const ROLE = "nabz";
const ENV_LOCAL = resolve(process.cwd(), ".env.local");
const BOOTSTRAP_FILE = resolve(process.cwd(), ".env.bootstrap.local");

/** URL-safe random secret (no characters that need escaping in URLs or .env files). */
const secret = (bytes: number) => randomBytes(bytes).toString("base64url");

function readEnvFile(path: string): Map<string, string> {
  const map = new Map<string, string>();
  if (!existsSync(path)) return map;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (m?.[1] && m[2] !== undefined) map.set(m[1], m[2].replace(/^"(.*)"$/, "$1"));
  }
  return map;
}

runScript(async () => {
  loadLocalEnv(".env.bootstrap.local");
  const superUrl = process.env.PG_SUPERUSER_URL;
  if (!superUrl) {
    throw new Error(
      "PG_SUPERUSER_URL is not set. Put it in .env.bootstrap.local:\n  PG_SUPERUSER_URL=postgres://postgres:<password>@127.0.0.1:5432/postgres",
    );
  }
  const admin = parseDatabaseUrl(superUrl);
  if (!["localhost", "127.0.0.1", "::1", "[::1]"].includes(admin.host)) {
    throw new Error(`Bootstrap only runs against a local Postgres, not "${admin.host}".`);
  }

  const existing = readEnvFile(ENV_LOCAL);
  // Keep the existing role password if .env.local already has one, so re-runs don't break the app.
  const existingUrl = existing.get("DATABASE_URL");
  const rolePassword = existingUrl ? decodeURIComponent(new URL(existingUrl).password) : secret(24);

  const client = new pg.Client({ connectionString: superUrl });
  await client.connect();
  try {
    const { rows: version } = await client.query<{ server_version: string }>("show server_version");
    console.log(`Connected to PostgreSQL ${version[0]?.server_version} on ${admin.host}:${admin.port}`);

    const roleExists =
      (await client.query("select 1 from pg_roles where rolname = $1", [ROLE])).rowCount === 1;
    const pw = client.escapeLiteral(rolePassword);
    if (roleExists) {
      await client.query(`alter role ${ROLE} with login nosuperuser nocreatedb nocreaterole password ${pw}`);
      console.log(`✓ role "${ROLE}" exists (password synced with .env.local)`);
    } else {
      await client.query(`create role ${ROLE} with login nosuperuser nocreatedb nocreaterole password ${pw}`);
      console.log(`✓ created role "${ROLE}"`);
    }

    for (const db of LOCAL_DATABASES) {
      const exists =
        (await client.query("select 1 from pg_database where datname = $1", [db])).rowCount === 1;
      if (exists) {
        console.log(`✓ database "${db}" exists`);
        continue;
      }
      try {
        // Match Neon's C.UTF-8 collation so sorting behaves the same locally and in production.
        await client.query(
          `create database ${db} owner ${ROLE} template template0 encoding 'UTF8' locale_provider builtin builtin_locale 'C.UTF-8'`,
        );
      } catch {
        await client.query(`create database ${db} owner ${ROLE} template template0 encoding 'UTF8'`);
      }
      console.log(`✓ created database "${db}"`);
    }
  } finally {
    await client.end();
  }

  const url = (db: string) =>
    `postgres://${ROLE}:${encodeURIComponent(rolePassword)}@127.0.0.1:${admin.port}/${db}`;

  const values: [string, string][] = [
    ["DATABASE_URL", url("nabz_dev")],
    ["DATABASE_URL_TEST", url("nabz_test")],
    ["NABZ_MODE", existing.get("NABZ_MODE") ?? "testing"],
    ["ALLOWED_NUMBERS", existing.get("ALLOWED_NUMBERS") ?? ""],
    ["CALLING_ENABLED", existing.get("CALLING_ENABLED") ?? "false"],
    ["BOLNA_DAILY_SPEND_CAP_USD", existing.get("BOLNA_DAILY_SPEND_CAP_USD") ?? "10"],
  ];
  const known = new Set(values.map(([k]) => k));
  const extra = [...existing].filter(([k]) => !known.has(k));

  const body = [
    "# Local secrets and settings. Never commit this file. Generated by `pnpm db:bootstrap`.",
    ...values.map(([k, v]) => `${k}=${v}`),
    ...extra.map(([k, v]) => `${k}=${v}`),
    "",
  ].join("\n");
  writeFileSync(ENV_LOCAL, body, { encoding: "utf8", mode: 0o600 });
  console.log("✓ wrote .env.local");

  if (existsSync(BOOTSTRAP_FILE)) {
    rmSync(BOOTSTRAP_FILE);
    console.log("✓ deleted .env.bootstrap.local (the superuser password is no longer stored)");
  }

  console.log("\nNext: pnpm db:setup");
});
